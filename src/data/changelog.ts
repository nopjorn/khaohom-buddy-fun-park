/** เทียบเลขรุ่นแบบ x.y.z คืนค่าลบถ้า a เก่ากว่า b */
export function compareVersions(a: string, b: string): number {
  const pa = a.split('.').map(Number);
  const pb = b.split('.').map(Number);
  for (let i = 0; i < 3; i++) {
    const diff = (pa[i] ?? 0) - (pb[i] ?? 0);
    if (diff !== 0) return diff;
  }
  return 0;
}

/**
 * รุ่นที่ผู้เล่นยังไม่เคยเห็นหลังอัปเดต ใช้ตัดสินว่าจะเด้งบอกหรือไม่
 * seen ว่างแปลว่าข้อมูลมาจากรุ่นก่อนที่จะจำรุ่นที่เห็น ถ้าเครื่องนี้ไม่เคยเล่นเลยถือว่าติดตั้งใหม่ จึงไม่ต้องบอก
 */
export function unseenChanges(
  log: ChangeEntry[],
  current: string,
  seen: string,
  freshInstall: boolean,
): ChangeEntry[] {
  if (!seen && freshInstall) return [];
  const newer = log.filter((e) => compareVersions(e.version, current) <= 0);
  if (!seen) return newer.slice(0, 1);
  return newer.filter((e) => compareVersions(e.version, seen) > 0);
}
